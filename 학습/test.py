# 테스트 실행 (수정 금지)
# =====================================================
def run_tests():
    results = []

    def test(name, got, expected):
        ok = got == expected
        status = "✅ PASS" if ok else "❌ FAIL"
        results.append(ok)
        if not ok:
            print(f"{status} [{name}]  expected={expected}, got={got}")
        else:
            print(f"{status} [{name}]")

    print("\n" + "="*50)
    print("1. 혼자 놀기의 달인")
    print("="*50)
    # 그룹: [4, 3, 1] → 4*3=12
    test("예시1", 혼자놀기의달인([8,6,3,7,2,5,1,4]), 12)
    # 그룹이 1개뿐이면 0
    test("예시2 (그룹 1개)", 혼자놀기의달인([1,2,3,4,5]), 0)

    print("\n" + "="*50)
    print("2. 영어 끝말잇기")
    print("="*50)
    test("예시1", 영어끝말잇기(3, ["tank","kick","know","wheel","land","dream","mother","robot","tank"]), [3,3])
    test("예시2", 영어끝말잇기(5, ["hello","observe","effect","take","either","recognize","encourage","ensure","establish","hang","gather","refer","reference","estimate","executive"]), [0,0])
    test("예시3", 영어끝말잇기(2, ["hello","one","even","never","now","world","draw"]), [1,3])

    print("\n" + "="*50)
    print("3. 피로도")
    print("="*50)
    test("예시1", 피로도(80, [[80,20],[50,40],[30,10]]), 3)
    test("예시2", 피로도(120, [[100,99],[20,5],[30,10]]), 3)

    print("\n" + "="*50)
    print("4. 소수 찾기")
    print("="*50)
    test("예시1", 소수찾기("17"), 3)   # 1, 7, 17 → 7, 17 소수 (1 제외) → 7, 17 → 3? 아니면 7,17,71? → 3
    test("예시2", 소수찾기("011"), 2)  # 0,1,11,10,101,110,011 → 소수: 11, 101 → 2

    print("\n" + "="*50)
    print("5. 지게차와 크레인")
    print("="*50)
    test("예시1", 지게차와크레인(["AZWQY","CBDOX","DEFGZ","GHIJW","IJKLX"], ["A","AB","ZA"]), 10)
    test("예시2", 지게차와크레인(["ABC","BCA","CAB"], ["AB","CA"]), 6)

    print("\n" + "="*50)
    passed = sum(results)
    total = len(results)
    print(f"결과: {passed}/{total} 통과")
    print("="*50 + "\n")


if __name__ == '__main__':
    run_tests()
